import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';
import { Database } from '@/integrations/supabase/types';
import { useAuth } from '@/context/AuthContext';

type Order = Database['public']['Tables']['orders']['Row'];
type OrderItem = Database['public']['Tables']['order_items']['Row'];
type OrderStatus = Database['public']['Enums']['order_status'];

interface OrderWithDetails extends Order {
  stores?: Database['public']['Tables']['stores']['Row'] | null;
  order_items?: OrderItem[];
  rider?: Database['public']['Tables']['profiles']['Row'] | null;
}

export const useOrders = () => {
  const { profile } = useAuth();

  return useQuery({
    queryKey: ['orders', profile?.id],
    queryFn: async () => {
      if (!profile) return [];

      const { data, error } = await supabase
        .from('orders')
        .select(`
          *,
          stores(*),
          order_items(*),
          rider:profiles!orders_rider_id_fkey(*)
        `)
        .eq('customer_id', profile.id)
        .order('created_at', { ascending: false });

      if (error) throw error;
      return data as OrderWithDetails[];
    },
    enabled: !!profile,
  });
};

export const useOrder = (orderId: string) => {
  return useQuery({
    queryKey: ['order', orderId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from('orders')
        .select(`
          *,
          stores(*),
          order_items(*),
          rider:profiles!orders_rider_id_fkey(*),
          customer:profiles!orders_customer_id_fkey(*)
        `)
        .eq('id', orderId)
        .maybeSingle();

      if (error) throw error;
      if (!data) throw new Error('Order not found or access denied');
      return data as OrderWithDetails & { customer?: { full_name?: string; phone?: string } };
    },
    enabled: !!orderId,
    retry: (failureCount, error) => {
      // Don't retry if order not found / access denied
      if (error?.message?.includes('Order not found')) return false;
      return failureCount < 2;
    },
  });
};

